def self_test() -> int:
    import tempfile

    failures: list[str] = []
    with tempfile.TemporaryDirectory() as td:
        root = Path(td)
        for name, body in SELF_TEST_FILES.items():
            (root / name).write_text(body, encoding="utf-8")
        found = extract(root)

    flat = {(src, kind, tok) for src, entries in found.items() for kind, tok in entries}
    tokens = {tok for _, _, tok in flat}

    for want in sorted(SELF_TEST_MUST_FIND):
        if want not in flat:
            failures.append(f"MISSED  {want[0]:38} {want[1]:5} {want[2]}")
    for bad in sorted(SELF_TEST_MUST_NOT_FIND):
        if bad in tokens:
            where = sorted(s for s, _, t in flat if t == bad)
            failures.append(f"FALSE+  {bad!r} extracted from {where}")

    # normalise(): the alias table and the foreign-namespace rule are both load-bearing.
    checks = [("WATER_LILY", "lily_pad"), ("Iron_Ore", "iron_ore"),
              ("minecraft:stone", "stone"), ("somemod:stone", None), ("  ", None)]
    for raw, want in checks:
        got = normalise(raw)
        if got != want:
            failures.append(f"NORM    normalise({raw!r}) = {got!r}, want {want!r}")

    # FAIL-CLOSED: an unclassified Bonus_Drops sub-section must REFUSE, not be skipped. Silently
    # skipping is how a future `Bonus_Drops.Excavation` would ship entirely unaudited while this
    # gate printed a clean run -- and a guard that cannot fail detects nothing. Asserting the raise
    # is the only way to know the branch is reachable; without this the whole block is dead code
    # that a later refactor deletes with nothing going red.
    with tempfile.TemporaryDirectory() as td:
        root = Path(td)
        for name, body in SELF_TEST_FILES.items():
            (root / name).write_text(body, encoding="utf-8")
        (root / "config.yml").write_text(SELF_TEST_UNCLASSIFIED, encoding="utf-8")
        try:
            extract(root)
            failures.append("CLOSED  an unclassified Bonus_Drops section did NOT raise")
        except SystemExit as e:
            if "Excavation" not in str(e) or "BONUS_DROP_KIND" not in str(e):
                failures.append(f"CLOSED  refused, but the message names neither the section nor "
                                f"the map to fix: {e}")

    print("=== SELF-TEST ===")
    print(f"  fixture produced {len(flat)} references across {len(found)} sections")
    if failures:
        print(f"  FAIL -- {len(failures)} problem(s):")
        for f in failures:
            print(f"      {f}")
        return 1
    print(f"  PASS -- {len(SELF_TEST_MUST_FIND)} required refs found, "
          f"{len(SELF_TEST_MUST_NOT_FIND)} non-id tokens correctly ignored, "
          f"{len(checks)} normalisation cases correct.")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--mc", action="append", metavar="VERSION",
                    help="report only this version (repeatable); default is every version in "
                         "scripts/mc-ids.txt. ⚠️ This narrows the REPORT, never the "
                         "DEAD-EVERYWHERE judgement -- see the comment in run()")
    ap.add_argument("--control", metavar="VERSION",
                    help="version every id must resolve on (default: gradle.properties pin)")
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if any id is dead on every version or fails the control")
    ap.add_argument("--self-test", action="store_true",
                    help="prove the extractor fires and stays quiet on non-ids, then exit")
    args = ap.parse_args()

    if args.self_test:
        return self_test()

    control = args.control or pinned_version()
    versions = args.mc or supported_versions()
    if not versions:
        raise SystemExit("scripts/mc-ids.txt lists no versions -- nothing to audit")
    return run(versions, control, args.check)


def supported_versions() -> list[str]:
    """Every version in the manifest — the DEAD-EVERYWHERE comparison set.

    ⚠️ Deliberately NOT `cached_versions()`. That was this machine's Loom cache, so the verdict
    "dead on every supported version" silently meant "dead on every version I happened to have
    built against" — a different question, with a different answer on every checkout. The manifest
    is committed, so the comparison set is now the same everywhere, including on a band branch that
    has only ever built one version.
    """
    return sorted(manifest(), key=lambda v: [int(x) for x in re.findall(r"\d+", v)])


if __name__ == "__main__":
    sys.exit(main())
